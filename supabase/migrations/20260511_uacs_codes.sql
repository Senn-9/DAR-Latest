-- Enable pg_trgm for fuzzy / trigram search (no-op if already enabled)
create extension if not exists pg_trgm;

-- UACS Object Codes lookup table
create table if not exists public.uacs_codes (
  id          serial primary key,
  uacs_code   text not null unique,
  description text not null,
  created_at  timestamptz default now()
);

-- Fast prefix / similarity indexes
create index if not exists uacs_codes_code_idx on public.uacs_codes using gin (uacs_code gin_trgm_ops);
create index if not exists uacs_codes_desc_idx on public.uacs_codes using gin (description gin_trgm_ops);

